#!/usr/bin/env node
/*
 * Generates `apps/website/docs/contrast-matrix.md` from the same source the
 * Showcase Surface badges read. One TS function, two outputs — impossible for
 * the committed matrix to disagree with the rendered badges. See ADR-0002 §8.
 *
 * Usage: pnpm contrast-matrix
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { DOCUMENTED_PAIRS, evaluatePair } from '../src/lib/contrast.ts';

const here = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(here, '../docs/contrast-matrix.md');

const header = [
  '# Contrast matrix',
  '',
  '> Generated by `pnpm contrast-matrix` from `apps/website/src/lib/contrast.ts`.',
  '> Do not edit by hand — re-run the script after token or pair changes.',
  '',
  '| Foreground | Background | Ratio | AA | AAA |',
  '| --- | --- | --- | --- | --- |',
];

const rows = DOCUMENTED_PAIRS.map((p) => {
  const { ratio, passesAA, passesAAA } = evaluatePair(p.fgHex, p.bgHex);
  return `| \`${p.fgName}\` | \`${p.bgName}\` | ${ratio.toFixed(2)}:1 | ${passesAA ? 'PASS' : 'FAIL'} | ${passesAAA ? 'PASS' : 'FAIL'} |`;
});

const body = [...header, ...rows, ''].join('\n');

await mkdir(dirname(outPath), { recursive: true });
await writeFile(outPath, body, 'utf8');

console.info(`Wrote ${rows.length} pair${rows.length === 1 ? '' : 's'} → ${outPath}`);
